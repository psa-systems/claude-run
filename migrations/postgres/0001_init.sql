-- CLAUDE-250: the whole schema in one migration, for a PostgreSQL backend.
--
-- This is the end state of the twenty SQLite migrations in `../sqlite/`, not a
-- replay of them: a Postgres database is new by definition here (copying an
-- existing `state.db` across is CLAUDE-251), so nothing is renamed, altered or
-- backfilled. Table names, column names and index names match the SQLite chain
-- exactly, because every query in `src/` is shared between the two backends.
--
-- Type mapping, chosen so no bind or decode site has to know which backend it
-- is talking to:
--   SQLite INTEGER -> BIGINT           (the code binds and decodes `i64`)
--   SQLite REAL    -> DOUBLE PRECISION (the code binds and decodes `f64`)
--   SQLite BLOB    -> BYTEA
--   INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT GENERATED BY DEFAULT AS IDENTITY
-- Boolean-ish columns stay integer 0/1 rather than becoming BOOLEAN: sqlx's
-- `Any` driver reports a Postgres BOOLEAN and a SQLite INTEGER as different
-- kinds, so a real BOOLEAN here would need a second decode path in every row
-- struct. `global_pause.id` and `web_admin.id` are plain BIGINT, not identity
-- columns, because both are single-row tables whose id is written explicitly.
-- BY DEFAULT rather than ALWAYS so an explicit id is accepted, which is what
-- SQLite's INTEGER PRIMARY KEY AUTOINCREMENT does; no runtime code writes one
-- (every insert takes the generated value back through RETURNING), but test
-- fixtures seed known ids and refusing them would make the two backends behave
-- differently under the same statement.

CREATE TABLE IF NOT EXISTS attempt_counters (
    action_name TEXT NOT NULL,
    job_key TEXT NOT NULL,
    count BIGINT NOT NULL,
    last_at TEXT NOT NULL,
    PRIMARY KEY (action_name, job_key)
);

CREATE TABLE IF NOT EXISTS daily_ledger (
    action_name TEXT NOT NULL,
    date TEXT NOT NULL,
    run_count BIGINT NOT NULL DEFAULT 0,
    cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    PRIMARY KEY (action_name, date)
);

CREATE TABLE IF NOT EXISTS runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_name TEXT NOT NULL,
    started_at TEXT NOT NULL,
    ended_at TEXT,
    exit_code BIGINT,
    jobs_processed BIGINT NOT NULL DEFAULT 0,
    triggered_by TEXT NOT NULL DEFAULT 'cli',
    job_keys TEXT,
    current_job_key TEXT,
    stage TEXT,
    job_links TEXT
);

CREATE INDEX IF NOT EXISTS idx_runs_action_started ON runs(action_name, started_at);

CREATE TABLE IF NOT EXISTS job_outcomes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    action_name TEXT NOT NULL,
    job_key TEXT NOT NULL,
    attempt BIGINT NOT NULL,
    ts TEXT NOT NULL,
    ok BIGINT NOT NULL,
    claude_ran BIGINT NOT NULL,
    claude_ok BIGINT NOT NULL,
    claude_cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    attempt_counted BIGINT NOT NULL DEFAULT 1,
    summary TEXT,
    stream_log_path TEXT,
    duration_ms BIGINT,
    timed_out BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_job_outcomes_action_job ON job_outcomes(action_name, job_key);
CREATE INDEX IF NOT EXISTS idx_job_outcomes_run ON job_outcomes(run_id);
CREATE INDEX IF NOT EXISTS idx_job_outcomes_ts ON job_outcomes(ts);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS actions (
    name TEXT PRIMARY KEY,
    file_path TEXT NOT NULL,
    yaml_sha256 TEXT NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1,
    schedule_kind TEXT,           -- 'interval' | 'cron' | 'manual'
    schedule_spec TEXT,           -- '30m' / '*/30 * * * *' / NULL
    last_seen_at TEXT NOT NULL,
    parse_error TEXT,             -- non-null = YAML failed to load
    link_template TEXT,
    max_parallel BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS paused_actions (
    action_name TEXT PRIMARY KEY,
    paused_at TEXT NOT NULL,
    reason TEXT
);

CREATE TABLE IF NOT EXISTS global_pause (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    paused_at TEXT NOT NULL,
    reason TEXT
);

CREATE TABLE IF NOT EXISTS run_inflight_jobs (
    run_id BIGINT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    job_key TEXT NOT NULL,
    concurrency_key TEXT,
    PRIMARY KEY (run_id, job_key)
);

CREATE TABLE IF NOT EXISTS secrets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    ciphertext BYTEA NOT NULL,
    created_at TEXT NOT NULL,
    last_used_at TEXT
);

CREATE TABLE IF NOT EXISTS run_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT REFERENCES runs(id) ON DELETE CASCADE,
    action_name TEXT NOT NULL,
    ts TEXT NOT NULL,
    level TEXT NOT NULL,
    context TEXT,
    message TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_run_events_action_ts ON run_events(action_name, ts);
CREATE INDEX IF NOT EXISTS idx_run_events_run ON run_events(run_id);
CREATE INDEX IF NOT EXISTS idx_run_events_ts ON run_events(ts);

CREATE TABLE IF NOT EXISTS dependency_gate (
    action_name   TEXT   NOT NULL,
    job_key       TEXT   NOT NULL,
    blocked_until BIGINT NOT NULL, -- epoch ms; gate re-evaluates once now >= this
    signature     TEXT   NOT NULL, -- canonical unmet-blocker set (change => re-comment)
    updated_at    TEXT   NOT NULL, -- RFC 3339, last write
    blocked_since BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (action_name, job_key)
);

CREATE TABLE IF NOT EXISTS web_admin (
    id            BIGINT PRIMARY KEY CHECK (id = 1),
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    session_key   TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL
);
