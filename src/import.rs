/// How the import treats a target that already holds rows.
#[derive(Debug, Clone, Copy, Default)]
pub struct ImportOptions {
    /// Copy into a target that is not empty. Off by default: the expected move
    /// is into a fresh database, and a second import into a populated one
    /// duplicates history and fails on the primary keys half way through.
    pub allow_nonempty: bool,
}

/// One row of the per-table comparison the operator sees.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableReport {
    pub table: String,
    pub source_rows: i64,
    pub target_rows_before: i64,
    pub copied: i64,
    pub target_rows_after: i64,
}

#[derive(Debug, Clone, Default)]
pub struct ImportReport {
    pub tables: Vec<TableReport>,
}

impl ImportReport {
    pub fn total_copied(&self) -> i64 {
        self.tables.iter().map(|t| t.copied).sum()
    }

    /// The comparison table printed on stdout. Both sides are shown per table
    /// rather than a bare success line, because "it worked" is not something an
    /// operator can check afterwards without this.
    pub fn render(&self) -> String {
        let width = self
            .tables
            .iter()
            .map(|t| t.table.len())
            .chain(std::iter::once("table".len()))
            .max()
            .unwrap_or(5);
        let mut out = format!(
            "{:<width$}  {:>10}  {:>10}  {:>10}\n",
            "table",
            "source",
            "copied",
            "target",
            width = width
        );
        out.push_str(&format!(
            "{}  {}  {}  {}\n",
            "-".repeat(width),
            "-".repeat(10),
            "-".repeat(10),
            "-".repeat(10)
        ));
        for t in &self.tables {
            out.push_str(&format!(
                "{:<width$}  {:>10}  {:>10}  {:>10}\n",
                t.table,
                t.source_rows,
                t.copied,
                t.target_rows_after,
                width = width
            ));
        }
        out
    }
}

/// A source column: its name, and the Rust type its declared SQLite type maps
/// onto for the decode-and-rebind round trip.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Column {
    name: String,
    kind: ColumnKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ColumnKind {
    Int,
    Real,
    Blob,
    Text,
}

impl ColumnKind {
    /// SQLite's own affinity rules, in SQLite's own order (an `INT` anywhere in
    /// the declared type wins over a later `CHAR`), so the kind this returns is
    /// the kind the value was stored as.
    fn from_declared(declared: &str) -> Self {
        let d = declared.to_ascii_uppercase();
        if d.contains("INT") {
            ColumnKind::Int
        } else if d.contains("CHAR") || d.contains("CLOB") || d.contains("TEXT") {
            ColumnKind::Text
        } else if d.contains("BLOB") || d.is_empty() {
            ColumnKind::Blob
        } else if d.contains("REAL") || d.contains("FLOA") || d.contains("DOUB") {
            ColumnKind::Real
        } else {
            // NUMERIC affinity. Nothing in this schema has one; text round-trips
            // any of the values such a column could hold.
            ColumnKind::Text
        }
    }
}

/// Refuse an import whose source file IS the configured target. Without this
/// the default invocation (no `[database] url` set) would copy `state.db` into
/// itself and fail on its own primary keys half way through.
pub fn refuse_same_target(source: &Path, target: &DatabaseTarget) -> Result<()> {
    let DatabaseTarget::Sqlite(target_path) = target else {
        return Ok(());
    };
    // Compare canonicalized where possible so `./state.db` and an absolute path
    // are the same file; fall back to the literal path when either side does
    // not exist yet (the target file is created by `db::open`).
    let same = match (
        std::fs::canonicalize(source),
        std::fs::canonicalize(target_path),
    ) {
        (Ok(a), Ok(b)) => a == b,
        _ => source == target_path.as_path(),
    };
    if same {
        return Err(anyhow::anyhow!(
            "the configured state store IS the import source ({}); \
             set [database] url (or CLAUDE_RUN_DATABASE_URL) to the database you are importing INTO",
            source.display()
        )
        .into());
    }
    Ok(())
}

/// Open `path` read-only. Never `mode=rwc`: the source must come out of a
/// failed import unmodified, and creating it on a typo would import an empty
/// database over the operator's real one.
async fn open_source(path: &Path) -> Result<DbPool> {
    if !path.is_file() {
        return Err(anyhow::anyhow!("no SQLite state store at {}", path.display()).into());
    }
    sqlx::any::install_default_drivers();
    let url = format!("sqlite://{}?mode=ro", path.display());
    // One connection: nothing here is concurrent, and a second one buys only a
    // second file handle on a database someone may still be writing.
    AnyPoolOptions::new()
        .max_connections(1)
        .connect_with(AnyConnectOptions::from_str(&url)?)
        .await
        .map_err(|e| {
            anyhow::anyhow!(
                "opening {} read-only failed: {e}. Stop the daemon first: a read-only open \
                 cannot recover a write-ahead log left behind by a killed process",
                path.display()
            )
            .into()
        })
}

/// Copy every table from the SQLite file at `source_path` into `target`.
///
/// One transaction on the target: a failure at any table rolls the whole copy
/// back rather than leaving a half-populated database that looks startable.
pub async fn import_sqlite(
    source_path: &Path,
    target: &DbPool,
    opts: ImportOptions,
) -> Result<ImportReport> {
    let source = open_source(source_path).await?;
    let result = import_from_pool(&source, target, opts).await;
    source.close().await;
    result
}

/// [`import_sqlite`] with the source pool already open, split out so the file
/// handle is closed on the error path as well as on the success path.
async fn import_from_pool(
    source: &DbPool,
    target: &DbPool,
    opts: ImportOptions,
) -> Result<ImportReport> {
    let source_schema = sqlite_columns(source).await?;
    let target_schema = target_columns(target).await?;
    verify_schema(&source_schema, &target_schema)?;

    let mut tx = target.begin().await?;
    let mut before = BTreeMap::new();
    let mut populated = Vec::new();
    for table in TABLES {
        let n = count_rows_tx(&mut tx, table).await?;
        if n > 0 {
            populated.push(format!("{table} ({n})"));
        }
        before.insert(*table, n);
    }
    if !populated.is_empty() && !opts.allow_nonempty {
        return Err(anyhow::anyhow!(
            "the target database already holds rows: {}. Import into an empty database, \
             or pass --allow-nonempty to copy into it anyway",
            populated.join(", ")
        )
        .into());
    }

    let mut report = ImportReport::default();
    for table in TABLES {
        let columns = &source_schema[*table];
        let source_rows = count_rows(source, table).await?;
        let copied = copy_table(source, target, &mut tx, table, columns).await?;
        let after = count_rows_tx(&mut tx, table).await?;
        let expected = before[*table] + source_rows;
        // The verification the operator would otherwise have to do by hand, and
        // the only thing that distinguishes a real copy from a silent partial
        // one. A mismatch aborts before the commit.
        if copied != source_rows || after != expected {
            return Err(anyhow::anyhow!(
                "table {table}: copied {copied} of {source_rows} rows and the target holds \
                 {after}, expected {expected}; nothing was committed"
            )
            .into());
        }
        info!(table = %table, rows = copied, "table imported");
        report.tables.push(TableReport {
            table: (*table).to_string(),
            source_rows,
            target_rows_before: before[*table],
            copied,
            target_rows_after: after,
        });
    }

    reset_identity_sequences(target, &mut tx).await?;
    tx.commit().await?;
    Ok(report)
}

/// Copy one table. Rows are read in one pass and inserted one statement at a
/// time: the tables the retention sweep bounds are small, and a per-row insert
/// keeps the failing row's table and column in the error.
async fn copy_table(
    source: &DbPool,
    target: &DbPool,
    tx: &mut sqlx::Transaction<'_, sqlx::Any>,
    table: &str,
    columns: &[Column],
) -> Result<i64> {
    // Identifiers come from the source's own catalog, never from operator
    // input, so they are interpolated rather than bound (SQL binds values, not
    // identifiers, on either backend).
    let names = columns
        .iter()
        .map(|c| c.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let select = format!("SELECT {names} FROM {table}");
    let placeholders = vec!["?"; columns.len()].join(", ");
    let insert = format!("INSERT INTO {table} ({names}) VALUES ({placeholders})");
    let insert = db::q(target, &insert).into_owned();

    let rows = sqlx::query(&db::q(source, &select))
        .fetch_all(source)
        .await?;
    let mut copied = 0i64;
    for row in &rows {
        // CLAUDE-436: the Any driver types a NULL f64 bind as Postgres
        // float4, and sqlx caches a prepared statement's parameter types per
        // connection, so a NULL in a nullable REAL column on one row and a
        // real value in the same column on a later row of the same table
        // must not share a cached Parse.
        let mut query = sqlx::query(&insert).persistent(false);
        for (i, column) in columns.iter().enumerate() {
            query = match column.kind {
                ColumnKind::Int => query.bind(cell::<i64>(row, i, table, column)?),
                ColumnKind::Real => query.bind(cell::<f64>(row, i, table, column)?),
                ColumnKind::Blob => query.bind(cell::<Vec<u8>>(row, i, table, column)?),
                ColumnKind::Text => query.bind(cell::<String>(row, i, table, column)?),
            };
        }
        query.execute(&mut **tx).await?;
        copied += 1;
    }
    Ok(copied)
}

/// Decode one value, naming the table and column when it does not fit the type
/// its declared SQLite type promised.
fn cell<'a, T>(
    row: &'a sqlx::any::AnyRow,
    index: usize,
    table: &str,
    column: &Column,
) -> Result<Option<T>>
where
    T: sqlx::Decode<'a, sqlx::Any> + sqlx::Type<sqlx::Any>,
{
    row.try_get::<Option<T>, _>(index).map_err(|e| {
        anyhow::anyhow!(
            "{table}.{} (declared {:?}) did not decode: {e}",
            column.name,
            column.kind
        )
        .into()
    })
}

/// Advance each identity sequence past the ids just copied. Postgres only:
/// SQLite's `AUTOINCREMENT` reads `sqlite_sequence`, which it maintains itself
/// from the inserted ids.
async fn reset_identity_sequences(
    target: &DbPool,
    tx: &mut sqlx::Transaction<'_, sqlx::Any>,
) -> Result<()> {
    if db::dialect(target) != Dialect::Postgres {
        return Ok(());
    }
    for (table, column) in IDENTITY_COLUMNS {
        // `false` for `is_called`, so the sequence returns exactly this value
        // next; `MAX + 1` over an empty table leaves it at 1.
        let sql = format!(
            "SELECT setval(pg_get_serial_sequence('{table}', '{column}'), \
             COALESCE((SELECT MAX({column}) FROM {table}), 0) + 1, false)"
        );
        sqlx::query(&sql).execute(&mut **tx).await?;
    }
    Ok(())
}

async fn count_rows(pool: &DbPool, table: &str) -> Result<i64> {
    let n: i64 = sqlx::query_scalar(&db::q(pool, &format!("SELECT COUNT(*) FROM {table}")))
        .fetch_one(pool)
        .await?;
    Ok(n)
}

async fn count_rows_tx(tx: &mut sqlx::Transaction<'_, sqlx::Any>, table: &str) -> Result<i64> {
    // COUNT(*) needs no rewrite on either backend, so this reads the same
    // uncommitted state the copy is writing without going back to the pool.
    let n: i64 = sqlx::query_scalar(&format!("SELECT COUNT(*) FROM {table}"))
        .fetch_one(&mut **tx)
        .await?;
    Ok(n)
}

/// The source's tables and columns, in column order, from SQLite's own catalog.
async fn sqlite_columns(pool: &DbPool) -> Result<BTreeMap<String, Vec<Column>>> {
    let rows: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT m.name, p.name, p.type FROM sqlite_master m JOIN pragma_table_info(m.name) p \
         WHERE m.type = 'table' AND m.name NOT LIKE 'sqlite_%' ORDER BY m.name, p.cid",
    )
    .fetch_all(pool)
    .await?;
    let mut out: BTreeMap<String, Vec<Column>> = BTreeMap::new();
    for (table, column, declared) in rows {
        if table == MIGRATIONS_TABLE {
            continue;
        }
        out.entry(table).or_default().push(Column {
            name: column,
            kind: ColumnKind::from_declared(&declared),
        });
    }
    Ok(out)
}

/// The target's tables and column names. Two catalog reads, one per backend:
/// reading a schema is the one thing the two have no common spelling for, so
/// these (like the pair in `db.rs`) do not go through [`db::q`].
async fn target_columns(pool: &DbPool) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let rows: Vec<(String, String)> = match db::dialect(pool) {
        Dialect::Sqlite => {
            sqlx::query_as(
                "SELECT m.name, p.name FROM sqlite_master m JOIN pragma_table_info(m.name) p \
                 WHERE m.type = 'table' AND m.name NOT LIKE 'sqlite_%' ORDER BY 1, 2",
            )
            .fetch_all(pool)
            .await?
        }
        Dialect::Postgres => {
            sqlx::query_as(
                // Cast off `information_schema`'s `name` domain: the `Any`
                // driver maps only the plain scalar types.
                "SELECT table_name::text, column_name::text FROM information_schema.columns \
                 WHERE table_schema = current_schema() ORDER BY 1, 2",
            )
            .fetch_all(pool)
            .await?
        }
    };
    let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (table, column) in rows {
        if table == MIGRATIONS_TABLE {
            continue;
        }
        out.entry(table).or_default().insert(column);
    }
    Ok(out)
}

/// Refuse anything but an exact match between the two schemas.
///
/// Every problem is collected and reported at once, because an operator who has
/// to run the import once per missing column learns nothing on each pass. A
/// source older than the target is the expected failure here, and the message
/// says how to fix it: opening the file with this build applies the pending
/// SQLite migrations, which the read-only import deliberately cannot do.
fn verify_schema(
    source: &BTreeMap<String, Vec<Column>>,
    target: &BTreeMap<String, BTreeSet<String>>,
) -> Result<()> {
    let known: BTreeSet<&str> = TABLES.iter().copied().collect();
    let mut problems = Vec::new();

    let target_tables: BTreeSet<&str> = target.keys().map(|s| s.as_str()).collect();
    for missing in known.difference(&target_tables) {
        problems.push(format!("target is missing table `{missing}`"));
    }
    for extra in target_tables.difference(&known) {
        problems.push(format!(
            "target holds table `{extra}`, which this build does not know how to copy"
        ));
    }

    for table in TABLES {
        let Some(source_columns) = source.get(*table) else {
            problems.push(format!("source is missing table `{table}`"));
            continue;
        };
        let Some(target_columns) = target.get(*table) else {
            continue;
        };
        let source_names: BTreeSet<&str> = source_columns.iter().map(|c| c.name.as_str()).collect();
        let target_names: BTreeSet<&str> = target_columns.iter().map(|s| s.as_str()).collect();
        for missing in target_names.difference(&source_names) {
            problems.push(format!("source `{table}` is missing column `{missing}`"));
        }
        for extra in source_names.difference(&target_names) {
            problems.push(format!(
                "source `{table}` has column `{extra}`, which the target does not"
            ));
        }
    }

    if problems.is_empty() {
        return Ok(());
    }
    Err(anyhow::anyhow!(
        "the source schema does not match the target schema:\n  {}\n\
         A source older than this build is brought up to date by opening it once with it \
         (CLAUDE_RUN_DATABASE_URL=sqlite://<file> claude-run status), which runs the pending \
         SQLite migrations; the import itself opens the file read-only and cannot.",
        problems.join("\n  ")
    )
    .into())
}

