    #[test]
    fn declared_types_map_onto_the_sqlite_affinities() {
        assert_eq!(ColumnKind::from_declared("INTEGER"), ColumnKind::Int);
        assert_eq!(ColumnKind::from_declared("BIGINT"), ColumnKind::Int);
        assert_eq!(ColumnKind::from_declared("TEXT"), ColumnKind::Text);
        assert_eq!(ColumnKind::from_declared("BLOB"), ColumnKind::Blob);
        assert_eq!(ColumnKind::from_declared("REAL"), ColumnKind::Real);
        assert_eq!(
            ColumnKind::from_declared("DOUBLE PRECISION"),
            ColumnKind::Real
        );
        // INT wins over CHAR, as it does in SQLite's own affinity rules.
        assert_eq!(ColumnKind::from_declared("INT CHAR"), ColumnKind::Int);
    }
