//! Copy an existing SQLite state store into the configured backend.
//!
//! Selecting PostgreSQL only opens an empty instance: the
//! Postgres migration set is a squashed baseline and nothing moves rows, so an
//! operator switching backends lost every run, attempt counter, daily ledger
//! entry, setting, encrypted secret and web administrator. This is the copy.
//!
//! The source is ANY SQLite state store, not just the default `state.db`, and
//! it is opened READ-ONLY: a refused or failed import leaves the operator
//! exactly where they started, still able to run the daemon off the same file.
//! The target is whatever [`crate::config::resolve_database`] resolved, so the
//! import and the daemon can never disagree about where the rows went.
//!
//! The copy is schema-driven rather than typed per column: the source's own
//! `pragma_table_info` supplies the column list and its declared type, which
//! decides the Rust type each value is decoded and re-bound as. SQLite's column
//! affinity is what makes that sound (an INTEGER-affinity column stores an
//! integer, a TEXT-affinity column stores text), and a value that does not
//! decode is a hard error naming the table and column rather than a silent
//! coercion.

